<p>看完了瀑布，大家也都饿了，毫无疑问赶紧找吃的，但是大家都犯了难题，这马峦山上真的是人烟稀少，去哪里找吃的，又不可能下山，所以决定继续往上走。</p>
<img src="https://www.lincoln.com.cn/content/dam/lincoln/TerritoryActivity/WordOfMouthInformation/activity24.png">
<p>当你走到这片碧绿的湖时，就说明你离吃的不远了。首先说说这个湖，算得上是山上最大的，里面有很多大鱼，偶尔还会有几条直接跃出水面，这就是传说中的鲤跃龙门？</p>
<p>饿肚子的我们很快就发现了在这条小路的尽头有烟冒出来，作为吃货的我们觉得很有可能会有吃的，所以直接开车进去。</p>
<img src="https://www.lincoln.com.cn/content/dam/lincoln/TerritoryActivity/WordOfMouthInformation/activity25.png">
<p>这个农家乐没有牌匾，没有营业标志，唯一让我们确信是一家能吃饭的店的标志就是门框上面的会员8.8折优惠横幅。这是典型客家建筑，光从岭南世居四个字老化程度也知道它经历了不少的岁月，只不过老板娘其实是湖南人。</p>
<img src="https://www.lincoln.com.cn/content/dam/lincoln/TerritoryActivity/WordOfMouthInformation/activity26.png">
<p>定睛一看，其实吸引我们过来的烟是从这里来的，看起来像是某公司组织的拓展训练聚会，还有教官在旁边进行指导，大家一起动手协作，好不好吃就另说了。</p>
<img src="https://www.lincoln.com.cn/content/dam/lincoln/TerritoryActivity/WordOfMouthInformation/activity27.png">
<p>我们提前预测了一下菜的价格，肯定不会便宜，刚开始我只看到了一排三位数的价格，就觉得真是贵阿，在我的预料之内，但是接下来我发现自己被打脸了。</p>
<p>我们点了一只鸡，一个西红柿炒鸡蛋，一个炒红薯叶，接下来我们看到的就让我们觉得这顿饭超值。</p>
<img src="https://www.lincoln.com.cn/content/dam/lincoln/TerritoryActivity/WordOfMouthInformation/activity28.png">
<p>我们问了句鸡是现杀的吗，老板娘直接说跟我走，现去抓，并且我们现场就钦点了一只可怜的鸡，阿姨和老板娘用了网和盆在一起合力抓都没抓住，这只鸡直接飞了！</p>
<img src="https://www.lincoln.com.cn/content/dam/lincoln/TerritoryActivity/WordOfMouthInformation/activity29.png">
<p>所以我们只能换只鸡来吃，这次阿姨仅凭一人之力就直接网住一只，然后拎起翅膀准备宰杀，现场图我就不放上来了，免得引起不适。</p>
<img src="https://www.lincoln.com.cn/content/dam/lincoln/TerritoryActivity/WordOfMouthInformation/activity30.png">
<p>当然了，作为原生态的农家乐，炒的红薯叶也是老板娘亲自现场采摘，这就叫做看着放心，吃着舒心，在市内真的无法体会到这种感觉。</p>
<img src="https://www.lincoln.com.cn/content/dam/lincoln/TerritoryActivity/WordOfMouthInformation/activity31.png">
<p>而旁边的水池还有养的鱼，如果你点了鱼，就可以直接过来捞，自然的水养的鱼，是不是跟在鱼缸里打氧的鱼味道不一样呢？反正我们没点，下次可以尝尝。</p>
<img src="https://www.lincoln.com.cn/content/dam/lincoln/TerritoryActivity/WordOfMouthInformation/activity32.png">
<p>上菜是需要等久一点的，主要是这只鸡确实需要炖久一点，但是别说，一只鸡能炖出这么一大盘，真的属于超大量了，我们掂了一下，至少也得3斤左右吧，而且味道是真的非常不错，鲜鸡肉是能吃的出来的。</p>
<img src="https://www.lincoln.com.cn/content/dam/lincoln/TerritoryActivity/WordOfMouthInformation/activity33.png">
<p>最后我们三个人，这三个菜都没吃完，鸡至少还剩了一半，加上三瓶可乐，总共花费了225元！这个价格在市内也就够两个人吃次一般般的火锅，我们平均每人75元，但是这顿饭，至少是够5个人吃，现杀溜达鸡，现摘青菜，这个性价比我就不用多说了吧，如果来到马峦山，必须推荐你到这里吃。</p>
<p>在短暂的欣赏了这些有年代感的客家建筑之后，开始了下一步的探险之旅。</p>

<img src="https://www.lincoln.com.cn/content/dam/lincoln/TerritoryActivity/WordOfMouthInformation/activity34.png">
<p>这条路就是在我们吃鸡的地方往里走，是一条全路段单车道并且非常窄的路，我们是听说了有古建筑，所以决定进去看一看有没有什么意外惊喜。</p>
<img src="https://www.lincoln.com.cn/content/dam/lincoln/TerritoryActivity/WordOfMouthInformation/activity35.png">
<p>刚吃完午饭的我们稍微有点累，同事毫不犹豫的决定想躺在车上眯一会儿，放倒了领界的后排座椅，几乎全平，并且还有全景天窗，躺下之后他就来了一句：舒服。</p>
<img src="https://www.lincoln.com.cn/content/dam/lincoln/TerritoryActivity/WordOfMouthInformation/activity36.png">
<p>首先第一个让我们停下的地方就是左手边小湖，右手茅草屋的路段，这里的风景怎么看都格外安静，并且有些世外桃源般的感觉，除了天气有点热之外。</p>
<img src="https://www.lincoln.com.cn/content/dam/lincoln/TerritoryActivity/WordOfMouthInformation/activity37.png">
<p>顺着茅草屋路往里走，就是一个小湖，让人意外的是里面还有一群大鹅，这种场景真的让人感觉到非常惬意，尤其是对于长时间居住于钢筋水泥的我们来说，真的很放松。</p>
<img src="https://www.lincoln.com.cn/content/dam/lincoln/TerritoryActivity/WordOfMouthInformation/activity38.png">
<p>继续向前开，车道两侧的草变得越来越长，可以看出来这条路确实是长时间没人经过，好在我们的前进还算顺利，并且是有人下车提前探路，所以就决定继续探险。</p>
<img src="https://www.lincoln.com.cn/content/dam/lincoln/TerritoryActivity/WordOfMouthInformation/activity39.png">
<p>大概前行了几十米，遇到了一段小泥浆路，好在泥浆在用木棍什么探过之后发现不深，我们就压着之前车子压过的路肩顺利通过，切记，如果自驾车辆遇到泥浆路，一定要先用身边物品探一探路是不是比较软，否则很容易陷进去。</p>
<img src="https://www.lincoln.com.cn/content/dam/lincoln/TerritoryActivity/WordOfMouthInformation/activity40.png">
<p>走了一小段，又一次发现了一个湖，这个湖比较大，并且水很清，可以说是绝对的原生态了，大家可能已经发现了，这条小路上有非常多的小湖，甚至可以叫这条路叫‘沿湖路’了。</p>
<img src="https://www.lincoln.com.cn/content/dam/lincoln/TerritoryActivity/WordOfMouthInformation/activity41.png">
<p>过了这个湖，就是一个比较大的坡路，我们走着先上去探了一下路，发现上面并没有什么特别的景色，也没有掉头位置，所以决定不再前进，倒车回去。</p>
<p>事实上，这段路的探险在我们亲身体验之后，不建议大家重大蹈覆辙，首先，意义不大，里面除了三个湖，没啥好玩的，然后车辆一定不要开进去，因为没有调头位置，所以大家如果想进去看看还是徒步吧。</p>
<img src="https://www.lincoln.com.cn/content/dam/lincoln/TerritoryActivity/WordOfMouthInformation/activity42.png">
<p>讲实话，梅亭刚开始并不在我们的计划内，是我们在吃鸡的时候漂亮的老板娘告诉我们的，听说不远，就决定上去看一看，但是寻找的路途真的不容易，老板娘也只是告诉我们这里挺好玩，咱也不敢多问阿。</p>
<img src="https://www.lincoln.com.cn/content/dam/lincoln/TerritoryActivity/WordOfMouthInformation/activity43.png">
<p>但是，你想要找梅亭，除了导航，不问的话找到的可能性不大，因为从吃鸡的地方去梅亭目前正在修路，得压着路边的土路过去，不过当你误打误撞，看到上图的一条带铁栅栏的大坝时，就说明已经找到梅亭了。</p>
<img src="https://www.lincoln.com.cn/content/dam/lincoln/TerritoryActivity/WordOfMouthInformation/activity44.png">
<p>走过大坝之后就会有一个停车点，此时大家就可以把车停在这里，然后走上去，或者上方还有一个停车点，但是车位在假期的时候会比较紧张。</p>
<img src="https://www.lincoln.com.cn/content/dam/lincoln/TerritoryActivity/WordOfMouthInformation/activity45.png">
<p>我们就直接将车开了上来，此时梅亭就在山顶，看起来不大，只有一个小亭子，似乎看不到什么特别值得我们经验的地方，来都来了，一定要到上面看一样。</p>
<img src="https://www.lincoln.com.cn/content/dam/lincoln/TerritoryActivity/WordOfMouthInformation/activity46.png">
<p>登上梅亭的台阶有很多，比较考验体力，我们在登顶的时候已经经历了一天的酷暑，当时有30度左右，我狠了心咬咬牙一口气就爬了上去，但是注意，因为没有防护措施，大家在上去的时候一定要小心。</p>
<img src="https://www.lincoln.com.cn/content/dam/lincoln/TerritoryActivity/WordOfMouthInformation/activity47.png">
<p>梅亭是一个二层就够的风景亭，四角翘起，典型的亭式设计，但是好像跟历史渊源不大，不大的亭子在山头傲立，倒是有几分梅花的傲骨气质。</p>


<img src="https://www.lincoln.com.cn/content/dam/lincoln/TerritoryActivity/WordOfMouthInformation/activity48.png">
<p>当你登上梅亭的二楼后，你就会感觉你的努力都没有白费，眼前的美景真的是在深圳很难看见的，几乎没有水泥建筑在你眼前，只有山海。此刻整个人会完全沉浸在这样的美景当中，这就是这里的风景制高点，在这样的山头修一个亭子，可能是再明智不过的选择了吧。</p>
<img src="https://www.lincoln.com.cn/content/dam/lincoln/TerritoryActivity/WordOfMouthInformation/activity49.png">
<img src="https://www.lincoln.com.cn/content/dam/lincoln/TerritoryActivity/WordOfMouthInformation/activity50.png">
