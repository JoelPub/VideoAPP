<p>马峦山瀑布是目前深圳市内最大的瀑布，可能很多人都会好奇，深圳还会有瀑布？没错，确实鲜有耳闻，因为其还是处于未被开发的状态，更加贴近自然，所以我们过来的第一站就是过来找瀑布，但是寻找的过程真的不是很容易。</p>
<img src="https://www.lincoln.com.cn/content/dam/lincoln/TerritoryActivity/WordOfMouthInformation/activity15.png">
<p>首先进入马峦山就要先进行导航，跟着导航进入天峦湖，这个时候路就比较难走，你可能都会怀疑自己是否走错了路，因为这里的路根本不像是一个景区或者公园，但是别担心，就跟着导航走，上山。</p>
<img src="https://www.lincoln.com.cn/content/dam/lincoln/TerritoryActivity/WordOfMouthInformation/activity16.png">
<p>一直往上走之后来到一个三叉路口，记住，这个海天一色的石门就是通往马峦山的路口，可惜，它真的是没有什么特别明显的指示，而且还写着通往南坪快速，我们第一次就真的直接略过了它。</p>
<img src="https://www.lincoln.com.cn/content/dam/lincoln/TerritoryActivity/WordOfMouthInformation/activity17.png">
