<img src="https://www.lincoln.com.cn/content/dam/lincoln/TerritoryActivity/WordOfMouthInformation/activity18.png">
<p>顺着路和瀑布的声音往上走，你就会发现这条土路，你没看错，这就是通向瀑布的路，门口还有一个废弃的保安亭，前面就是一条100多米的路通到下面。</p>


